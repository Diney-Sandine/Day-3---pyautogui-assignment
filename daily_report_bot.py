import pyautogui
import time
from datetime import datetime

pyautogui.FAILSAFE = True
pyautogui.PAUSE = 0.5

print("Step 1: Open the google chrome browser...")
time.sleep(2)

pyautogui.hotkey('win', 'r',interval=0.1)
time.sleep(1)
pyautogui.write('chrome')
time.sleep(1)
pyautogui.press('enter')
time.sleep(2)
pyautogui.press('tab')
time.sleep(1)
pyautogui.press('enter')
time.sleep(2)

print("Step 2: opening the website - THE ICAI...")
pyautogui.write('https://www.icai.org/',interval=0.1)
time.sleep(1)
pyautogui.press('enter')
time.sleep(1)
pyautogui.hotkey('ctrl', 'a',interval=0.1)
time.sleep(1)
pyautogui.hotkey('ctrl', 'c',interval=0.1)
time.sleep(1)

print("Step 3: Opening the Excel file...")
time.sleep(1)
pyautogui.hotkey('win', 'r',interval=0.1)
time.sleep(1)
pyautogui.write('excel')
time.sleep(1)
pyautogui.press('enter')
time.sleep(1)
pyautogui.press('enter')
time.sleep(1)
pyautogui.write('date: ' + str(datetime.now().strftime("%d-%m-%Y %H:%M:%S")),interval=0.1)
time.sleep(1)
pyautogui.press('tab')
time.sleep(1)
pyautogui.hotkey('ctrl', 'v',interval=0.1)
time.sleep(1)
pyautogui.press('right')
time.sleep(1)
pyautogui.write('ICAI Website',interval=0.1)
time.sleep(0.5)
pyautogui.press('enter')
time.sleep(1)
pyautogui.screenshot('excel_screenshot.png')
time.sleep(1)
pyautogui.hotkey('ctrl', 's',interval=0.1)
time.sleep(1)
pyautogui.write('daily_report_2026-11-06.xlsx',interval=0.1)   
time.sleep(1)
pyautogui.press('enter')